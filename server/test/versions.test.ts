test("poetry.lock and uv.lock", () => {
  const poetry = `[[package]]\nname = "fastapi"\nversion = "0.110.0"\ndescription = "x"\n\n[package.dependencies]\nstarlette = ">=0.36"\n\n[[package]]\nname = "Starlette"\nversion = "0.36.3"\n\n[metadata]\nlock-version = "2.0"\n`;
  const p = get(poetry); assert.equal(p.format, "poetry.lock"); assert.equal(p.versions.get("fastapi"), "0.110.0"); assert.equal(p.versions.get("starlette"), "0.36.3");
  const uv = `version = 1\nrequires-python = ">=3.12"\n\n[[package]]\nname = "sqlmodel"\nversion = "0.0.22"\nsource = { registry = "https://pypi.org/simple" }\n`;
  const u = get(uv); assert.equal(u.format, "uv.lock"); assert.equal(u.versions.get("sqlmodel"), "0.0.22");
});
test("size cap and bad input", () => {
  assert.ok("error" in (parseVersionsInput("a==1\n".repeat(MAX_VERSIONS_BYTES / 4)) as any));
  assert.ok("error" in (parseVersionsInput(42) as any));
  assert.ok("error" in (parseVersionsInput("{not json") as any));
});
test("verdicts", () => {
  assert.equal(line("0.115.0"), "0.115"); assert.equal(line("^5.2.0"), "5");
  assert.equal(verdictFor("5.3.0", "5.3.0"), "exact");
  assert.equal(verdictFor("5.3.0", "^5.3.0"), "exact");
  assert.equal(verdictFor("5.3.0", "5.0.1"), "compatible");
  assert.equal(verdictFor("5.3.0", "4.21.2"), "mismatch");
  assert.equal(verdictFor("0.115.0", "0.110.0"), "mismatch");
  assert.equal(verdictFor("0.115.0", "0.115.4"), "compatible");
  assert.equal(verdictFor("5.3.0", undefined), "not_in_project");
  assert.equal(verdictFor("5.3.0", "*"), "compatible");
});
test("checkCompatibility warnings and tooling skip", () => {
  const c = checkCompatibility({ express: "5.3.0", helmet: "8.3.0", zod: "4.6.7", tsx: "4.23.15", "@types/node": "24.0.0" }, get({ express: "4.21.2", helmet: "8.3.0" }));
  assert.equal(c.overall, "mismatch");
  assert.equal(c.packages.length, 3);
  const e = c.packages.find((p) => p.package === "express")!;
  assert.equal(e.verdict, "mismatch"); assert.match(e.warning!, /tested on express 5\.x, you have 4\.x, APIs may differ/i);
  assert.equal(c.packages.find((p) => p.package === "zod")!.verdict, "not_in_project");
  assert.equal(checkCompatibility({ zod: "4.6.7" }, get({})).overall, "unknown");
  for (const p of c.packages) assert.ok(!/\u2014|\u2013/.test(p.warning ?? ""));
});
test("usage event records only a boolean for versions", () => {
  const ev = eventFor({ method: "tools/call", params: { name: "get_recipe", arguments: { id: "x", versions: "secret-lockfile-text" } } }, { name: "t", version: "1" }, false);
  assert.equal(ev.versions_provided, true);
  assert.ok(!JSON.stringify(ev).includes("secret"));
  assert.equal(eventFor({ method: "tools/call", params: { name: "get_recipe", arguments: { id: "x" } } }, { name: "t", version: "1" }, false).versions_provided, false);
});

const R = (id: string, pinned: Record<string, string>) => ({ id, title: id, summary: "express api", language: "typescript", runtime: "node", stack: ["express"], tags: [], pinned, setup: "", test: "", files: [], receipt: { status: "passed", ran_at: null, last_passed_at: null } });
const idx: RecipeIndex = { schema_version: 1, generated_at: "x", count: 2, recipes: [R("a-express5", { express: "5.3.0" }), R("b-express4", { express: "4.21.2" })] };
const h = createHandler(idx);
const call = async (name: string, args: object) => { const r = await h(new Request("http://x/mcp", { method: "POST", body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/call", params: { name, arguments: args } }) })); const j: any = await r.json(); return { err: j.result.isError, body: j.result.content[0].text }; };

test("tools: get_recipe compat on top, search boosts matching versions", async () => {
  const g = await call("get_recipe", { id: "a-express5", versions: { express: "4.19.0" } });
  assert.equal(Object.keys(JSON.parse(g.body))[0], "compatibility");
  assert.equal(JSON.parse(g.body).compatibility.packages[0].verdict, "mismatch");
  const plain = JSON.parse((await call("get_recipe", { id: "a-express5" })).body); assert.equal(plain.compatibility, undefined);
  const s = JSON.parse((await call("search_recipes", { query: "express", versions: "express==4.21.2" })).body);
  assert.equal(s.results[0].id, "b-express4"); assert.equal(s.results[0].compatibility.overall, "exact"); assert.equal(s.results[1].compatibility.overall, "mismatch");
  assert.equal(JSON.parse((await call("search_recipes", { query: "express" })).body).results[0].id, "a-express5");
  assert.equal((await call("get_recipe", { id: "a-express5", versions: 5 })).err, true);
});
