import { Project, SyntaxKind, StructureKind, VariableDeclarationKind, type SourceFile } from "ts-morph";

export function inMemoryProject() {
  return new Project({ useInMemoryFileSystem: true, compilerOptions: { strict: true, target: 99, module: 99 } });
}

/** Generate a typed API module from a route table. */
export function generateClient(project: Project, routes: { name: string; method: "GET" | "POST"; path: string; returns: string }[]) {
  const sf = project.createSourceFile("/gen/client.ts", "", { overwrite: true });
  sf.addStatements("// generated by codemod.ts, do not edit");
  sf.addInterface({ name: "Course", isExported: true, properties: [{ name: "id", type: "string" }, { name: "hours", type: "number" }] });
  sf.addVariableStatement({
    declarationKind: VariableDeclarationKind.Const, isExported: true,
    declarations: [{ name: "BASE_URL", initializer: '"/api"' }],
  });
  for (const r of routes) {
    sf.addFunction({
      kind: StructureKind.Function, name: r.name, isExported: true, isAsync: true,
      parameters: r.method === "POST" ? [{ name: "body", type: "unknown" }] : [],
      returnType: `Promise<${r.returns}>`,
      statements: [
        `const res = await fetch(BASE_URL + ${JSON.stringify(r.path)}, { method: "${r.method}"${r.method === "POST" ? ", body: JSON.stringify(body)" : ""} });`,
        `return (await res.json()) as ${r.returns};`,
      ],
    });
  }
  sf.formatText({ indentSize: 2 });
  return sf;
}

/** Codemod: rename an exported function everywhere and convert `var` to `const`. */
export function renameAndModernize(sf: SourceFile, from: string, to: string) {
  sf.getFunctionOrThrow(from).rename(to);
  for (const vs of sf.getVariableStatements()) if (vs.getDeclarationKind() === VariableDeclarationKind.Var) vs.setDeclarationKind(VariableDeclarationKind.Const);
  return sf;
}

/** Remove console.log calls. */
export function stripConsoleLogs(sf: SourceFile) {
  const calls = sf.getDescendantsOfKind(SyntaxKind.CallExpression).filter((c) => c.getExpression().getText() === "console.log");
  for (const c of calls.reverse()) c.getParentIfKind(SyntaxKind.ExpressionStatement)?.remove();
  return calls.length;
}

export const typeErrors = (project: Project) =>
  project.getPreEmitDiagnostics().map((d) => (typeof d.getMessageText() === "string" ? d.getMessageText() : (d.getMessageText() as { getMessageText(): string }).getMessageText()) as string);
