from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.table import Table
from docx.text.paragraph import Paragraph

STYLE = "Light Grid Accent 1"


def build_report(path, title, columns, rows):
    doc = Document()
    doc.add_heading(title, level=0)
    doc.add_heading("Summary", level=1)
    doc.add_paragraph(f"{len(rows)} data rows")

    table = doc.add_table(rows=1, cols=len(columns))
    table.style = STYLE
    for cell, name in zip(table.rows[0].cells, columns):
        cell.text = name
        cell.paragraphs[0].runs[0].bold = True
    for row in rows:
        for cell, value in zip(table.add_row().cells, row):
            cell.text = str(value)

    doc.add_page_break()
    doc.add_heading("Appendix", level=1)
    doc.add_paragraph("Generated by ProvenPin.").alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.save(str(path))
    return doc


def iter_block_items(doc):
    # python-docx keeps paragraphs and tables in separate lists, so walk the XML
    # body to recover the real document order.
    for child in doc.element.body.iterchildren():
        if child.tag == qn("w:p"):
            yield Paragraph(child, doc)
        elif child.tag == qn("w:tbl"):
            yield Table(child, doc)


def headings(doc):
    return [(p.style.name, p.text) for p in doc.paragraphs if p.style.name.startswith("Heading")]


def has_page_break(paragraph):
    return any(
        br.get(qn("w:type")) == "page"
        for run in paragraph.runs
        for br in run._r.findall(qn("w:br"))
    )
